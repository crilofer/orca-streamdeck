// Writes src/agent-logo-bitmaps.ts from agent-icons/*.png, so the key renderer can inline a
// logo into its SVG without touching the filesystem at runtime.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const icons = new URL('../agent-icons/', import.meta.url)
const entries = readdirSync(icons)
  .filter((name) => name.endsWith('.png'))
  .sort()
  .map((name) => `  '${name.slice(0, -4)}': '${readFileSync(new URL(name, icons)).toString('base64')}'`)

writeFileSync(
  new URL('../src/agent-logo-bitmaps.ts', import.meta.url),
  `// Generated by scripts/embed-agent-icons.mjs from agent-icons/*.png; do not edit by hand.\n` +
    `/** Agent kind to base64 PNG, for agents Orca pictures with a favicon rather than an SVG. */\n` +
    `export const AGENT_LOGO_BITMAPS: Record<string, string> = {\n${entries.join(',\n')}\n}\n`
)
console.log(`${entries.length} logos embedded`)
